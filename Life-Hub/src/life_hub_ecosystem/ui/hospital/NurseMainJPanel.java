        int selectedrow = tbCourses.getSelectionModel().getLeadSelectionIndex();

        if (selectedrow < 0 || selectedrow > size - 1) {
            return;
        }
        selectedPatient = (PatientProfile) tbCourses.getValueAt(selectedrow, 0);
        if (selectedPatient == null) {
            return;
        }
        refreshMealsTable();

