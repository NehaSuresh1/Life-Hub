    void refreshAptTable() {
        //clear supplier table
        int rc = tblmeds.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tblmeds.getModel()).removeRow(i);
        }

        ArrayList<Appointment> aptList = dp.getHosp().getAppointmentDirectory().getAppointmentsList(); // getAppointments(); //getHosp().getDoctorDirectory().getDoctorList();
        if (aptList.isEmpty()) {
            return;
        }
        for (Appointment apt : aptList) {
            if (apt.getDp().isMatch(dp.getPerson().getPersonId())) {

                Object[] row = new Object[3];
                row[0] = apt.getPp();

                row[1] = apt; //getTests() == null ? "None" : apt.getTests();
                row[2] = apt.isHasCompleted();
                ((DefaultTableModel) tblmeds.getModel()).addRow(row);
            }
        }
        selectedPatient = null;
        selectedAppointment = null;
    }

