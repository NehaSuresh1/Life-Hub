    private void tblmedsMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblmedsMousePressed
        // TODO add your handling code here:
        int size = tblmeds.getRowCount();
        int selectedrow = tblmeds.getSelectionModel().getLeadSelectionIndex();

        if (selectedrow < 0 || selectedrow > size - 1) {
            return;
        }
        selectedPatient = (PatientProfile) tblmeds.getValueAt(selectedrow, 0);
        selectedAppointment = (Appointment) tblmeds.getValueAt(selectedrow, 1);
        if (selectedPatient == null) {
            return;
        }
    }//GEN-LAST:event_tblmedsMousePressed

    private void btnSelectPatientActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSelectPatientActionPerformed
        // TODO add your handling code here:
        if (selectedAppointment == null) {
            JOptionPane.showMessageDialog(this, "Select an appointment to proceed!");
            return;
        }
        if (selectedAppointment.isHasCompleted()) {
            JOptionPane.showMessageDialog(this, "Encounter Completed, Please select a valid Encounter!");
            return;
        }
        EncounterJPanel patientMainJPanel = new EncounterJPanel(es, dp, selectedPatient, CardSequencePanel, this, selectedAppointment);
        CardSequencePanel.add("patient", patientMainJPanel);
        ((java.awt.CardLayout) CardSequencePanel.getLayout()).next(CardSequencePanel);

    }//GEN-LAST:event_btnSelectPatientActionPerformed

