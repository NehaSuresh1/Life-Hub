    private void tblTestsMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblTestsMousePressed
        // TODO add your handling code here:
        // Extracts the row (uaser account) in the table that is selected by the user
        int size = tblTests.getRowCount();
        int selectedrow = tblTests.getSelectionModel().getLeadSelectionIndex();

        if (selectedrow < 0 || selectedrow > size - 1) {
            return;
        }
        selectedTest = (LabTest) tblTests.getValueAt(selectedrow, 0);
        if (selectedTest == null) {
            return;
        }
    }//GEN-LAST:event_tblTestsMousePressed

