    void refreshTestsTable() {
//clear supplier table
        int rc = tblTests.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tblTests.getModel()).removeRow(i);
        }

        ArrayList<LabTest> tests = es.getLabTestDirectory().getLabTestsList(); //.getMedPlan().getAssociations();
        //ArrayList<TestReport> reports = pp.getTests();
        //ArrayList<LabTest> l3 = new ArrayList<LabTest>();
        //l3.retainAll(l3)
        for (LabTest test : tests) {

            Object[] row = new Object[1];
            row[0] = test; //.getAssociatedPersonProfile().getPerson().getName();
            ((DefaultTableModel) tblTests.getModel()).addRow(row);

        }
        selectedTest = null;
    }

    void refreshMedsTable() {
//clear supplier table
        int rc = tblmeds.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tblmeds.getModel()).removeRow(i);
        }
        ArrayList<Med> meds = es.getMedDirectory().getMedsList(); //

        for (Med med : meds) {
            Object[] row = new Object[1];
            row[0] = med; //.getAssociatedPersonProfile().getPerson().getName();
            ((DefaultTableModel) tblmeds.getModel()).addRow(row);
        }
        selectedMed = null;
    }

