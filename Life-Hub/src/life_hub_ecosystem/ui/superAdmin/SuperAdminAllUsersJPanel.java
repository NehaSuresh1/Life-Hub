    public SuperAdminAllUsersJPanel(UserAccountDirectory userAccountDirectory,JPanel cp) {
        initComponents();
        CardSequencePanel=cp;
        this.userAccountDirectory = userAccountDirectory;

        // Create the table model
        DefaultTableModel tableModel = new DefaultTableModel(
                new Object[][]{}, // initial data
                new String[]{"Username", "Role", "Enabled"} // column headers
        ) {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                return columnIndex == 2 ? Boolean.class : super.getColumnClass(columnIndex);
            }

            @Override
            public boolean isCellEditable(int row, int column) {
                return column == 2; // Allow editing only for the "Enabled" column
            }
        };

        // Populate the table with data from the UserAccountDirectory
        for (UserAccount userAccount : userAccountDirectory.getUserAccountList()) {
            tableModel.addRow(new Object[]{userAccount.getUserLoginName(), userAccount.getRole(), userAccount.getIsEnabled()});
        }

        //add model to table
         table = new JTable(tableModel); // Initialize table with the model
         
        setLayout(new BorderLayout());
        JScrollPane scrollPane = new JScrollPane(table);
        add(scrollPane, BorderLayout.CENTER);
        JPanel buttonPanel = new JPanel();
    buttonPanel.add(saveButton);
    buttonPanel.add(btnBack);

    add(buttonPanel, BorderLayout.SOUTH);


    }

    private void saveChanges() {
    int rowCount = table.getRowCount();

    for (int i = 0; i < rowCount; i++) {
        String username = (String) table.getValueAt(i, 0);
        boolean isEnabled = (Boolean) table.getValueAt(i, 2);

        // Iterate through the array to find the matching UserAccount by username
        UserAccount matchingUserAccount = null;
        for (UserAccount userAccount : userAccountDirectory.getUserAccountList()) {
            if (userAccount.getUserLoginName().equals(username)) {
                matchingUserAccount = userAccount;
                break; // Exit the loop once a match is found
            }
        }

        if (matchingUserAccount != null) {
            System.out.println("Before Update - UserAccount: " + matchingUserAccount.getUserLoginName() + " - Enabled: " + matchingUserAccount.getIsEnabled());
            matchingUserAccount.setIsEnabled(isEnabled);
            System.out.println("After Update - UserAccount: " + matchingUserAccount.getUserLoginName() + " - Enabled: " + matchingUserAccount.getIsEnabled());
        }
    }

    // Save changes to the directory or a file, e.g., serialize and save to a file
    // For simplicity, we'll just print the updated list here
    System.out.println("Updated User Account List:");
    for (UserAccount userAccount : userAccountDirectory.getUserAccountList()) {
        System.out.println(userAccount.getUserLoginName() + " - Enabled: " + userAccount.getIsEnabled());
    }

    JOptionPane.showMessageDialog(this, "Changes saved successfully");
}


