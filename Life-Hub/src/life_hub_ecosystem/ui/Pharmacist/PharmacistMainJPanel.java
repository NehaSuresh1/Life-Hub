    void refreshOrdersTable() {
//clear supplier table
        int rc = tblOrders.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tblOrders.getModel()).removeRow(i);
        }
        ArrayList<PharmaOrder> orders = es.getPharmaOrderDirectory().getOrdersList(); //

        for (PharmaOrder po : orders) {
            Object[] row = new Object[5];
            row[0] = po; //.getAssociatedPersonProfile().getPerson().getName();
            row[1] = po.getPp();
            row[2] = po.getDp();
            row[3] = po.getmedsList().getAssociations().keySet();
            row[4] = po.getIsActive();
            ((DefaultTableModel) tblOrders.getModel()).addRow(row);
        }
        selectedOrder = null;
    }

