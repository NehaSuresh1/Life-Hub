    private void btnCompleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompleteActionPerformed
        // TODO add your handling code here:
        String cost = txtCost.getText();
        if (selectedOrder == null) {
            JOptionPane.showMessageDialog(this, "Please select a order to proceed!");
            return;
        }
        if (cost == null) {
            JOptionPane.showMessageDialog(this, "Cost Required!");
            return;
        }
        selectedOrder.setCost(cost);
        selectedOrder.setIsActive(true);
        if (selectedOrder.getPp().getActiveMedPlan() == null) {
            selectedOrder.getPp().addMedPlan(selectedOrder.getmedsList());
            selectedOrder.getApt().setMedPlan(selectedOrder.getmedsList());
        } else {
            selectedOrder.getPp().getActiveMedPlan().setIsActive(false);
            selectedOrder.getPp().addMedPlan(selectedOrder.getmedsList());
            selectedOrder.getApt().setMedPlan(selectedOrder.getmedsList());
        }

        JOptionPane.showMessageDialog(this, "Order was fulfiled successfully!");
//        ArrayList<PharmaOrder> orders = es.getPharmaOrderDirectory().getOrdersList();
//        if (!orders.isEmpty()) {
//            orders.remove(selectedOrder);
//        }
        refreshOrdersTable();
    }//GEN-LAST:event_btnCompleteActionPerformed


