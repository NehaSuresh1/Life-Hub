    private void tblOrdersMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblOrdersMousePressed
        // TODO add your handling code here:
        // Extracts the row (uaser account) in the table that is selected by the user
        int size = tblOrders.getRowCount();
        int selectedrow = tblOrders.getSelectionModel().getLeadSelectionIndex();
        if (selectedrow < 0 || selectedrow > size - 1) {
            return;
        }
        selectedOrder = (PharmaOrder) tblOrders.getValueAt(selectedrow, 0);
        if (selectedOrder == null) {
            return;

        }
    }//GEN-LAST:event_tblOrdersMousePressed

