    private void btnCompleteTestActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompleteTestActionPerformed
        // TODO add your handling code here:
        if (selectedOrder == null) {
            JOptionPane.showMessageDialog(this, "Select a test to proceed!");
            return;
        }
        if (tr == null || tr.getPp().getPerson().getPersonId() != selectedPP.getPerson().getPersonId()) {
            newTR();
        }

        //selectedOrder.setLabTestsList(
        tr.addTest(selectedTest, dropResult.getSelectedItem().toString());
        selectedOrder.removeTest(selectedTest);
        refreshOrdersTable();
    }//GEN-LAST:event_btnCompleteTestActionPerformed


