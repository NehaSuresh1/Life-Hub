    void refreshOrdersTable() {
//clear supplier table
        int rc = tblOrders.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tblOrders.getModel()).removeRow(i);
        }
        ArrayList<LabOrder> orders = es.getLabOrdersDirectory().getOrdersList(); //

        for (LabOrder lo : orders) {
            ArrayList<LabTest> lts = lo.getLabTestsList();
            for (LabTest lt : lts) {
                Object[] row = new Object[4];
                row[0] = lo; //.getAssociatedPersonProfile().getPerson().getName();
                row[1] = lt;
                row[2] = lo.getPp();
                row[3] = lo.getDp();
                ((DefaultTableModel) tblOrders.getModel()).addRow(row);
            }
        }

        selectedTest = null;
    }

