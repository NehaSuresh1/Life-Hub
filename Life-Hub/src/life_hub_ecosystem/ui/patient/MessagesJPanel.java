    public void refreshTable() {
//clear supplier table
        int rc = tbCourses.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tbCourses.getModel()).removeRow(i);
        }

        ArrayList<Message> msgs = pp.getHosp().getMessageDirectory().getMsgsList();
        if(msgs.isEmpty()){
            return;
        }
        for (Message msg : msgs) {
            if (msg.getPp().isMatch(pp.getPerson().getPersonId())) {
                Object[] row = new Object[3];
                row[0] = msg.getInfo();
                row[1] = msg.getNp();
                row[2] = msg.getDate();
            }
        }

    }

