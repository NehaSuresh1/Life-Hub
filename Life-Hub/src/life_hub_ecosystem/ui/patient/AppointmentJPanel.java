    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
        // TODO add your handling code here:
        if (selectedCDoc == null) {
            JOptionPane.showMessageDialog(this, "Select a doctor to register!");
            return;
        }
//        if (selectedCDoc.findRegisteredStudent(sp) != null) {
//            JOptionPane.showMessageDialog(this, "Already registered for the course!");
//            return;
//        }
        //selectedCDoc.registerStudent(sp);
        ArrayList<Appointment> aptList = selectedCDoc.getHosp().getAppointmentDirectory().getAppointmentsList();//.remove(ui);
        if (!aptList.isEmpty()) {
            for (Appointment apt : aptList) {
                if (selectedCDoc.isMatch(apt.getDp().getPerson().getPersonId()) && pp.isMatch(apt.getPp().getPerson().getPersonId()) && !apt.isHasCompleted()) {
                    JOptionPane.showMessageDialog(this, "Already a appoitnment with  " + selectedCDoc.getPerson().getName() + " exists");
                    return;
                }
            }
        }
        Appointment apt = pp.getHosp().getAppointmentDirectory().newApt(selectedCDoc, pp);
        pp.addAppointments(apt);
        JOptionPane.showMessageDialog(this, "Successfully Booked an appointment with  " + selectedCDoc.getPerson().getName());
        refreshAptTable();
        // to be continued
    }//GEN-LAST:event_btnRegisterActionPerformed

    private void tbCoursesMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbCoursesMousePressed
        // TODO add your handling code here:
        int size = tbCourses.getRowCount();
        int selectedrow = tbCourses.getSelectionModel().getLeadSelectionIndex();

        if (selectedrow < 0 || selectedrow > size - 1) {
            return;
        }
        selectedCDoc = (DoctorProfile) tbCourses.getValueAt(selectedrow, 0);
        if (selectedCDoc == null) {
            return;

        }
    }//GEN-LAST:event_tbCoursesMousePressed

