    void refreshDocTable() {
//clear supplier table
        int rc = tbCourses.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tbCourses.getModel()).removeRow(i);
        }

        ArrayList<DoctorProfile> docList = pp.getHosp().getDoctorDirectory().getDoctorList();

        for (DoctorProfile doc : docList) {

            Object[] row = new Object[4];
            row[0] = doc; //.getAssociatedPersonProfile().getPerson().getName();
            row[1] = doc.getDept().getDeptName();
            row[2] = doc.getExperience(); //doc.getHighestQulification().getFacultyProfile(); //ua.getAssociatedPersonProfile().getPerson().getName();
            row[3] = doc.getHighestQulification(); //ua.getRole();
            ((DefaultTableModel) tbCourses.getModel()).addRow(row);
        }
        selectedCDoc = null;
    }

    void refreshAptTable() {
        //clear supplier table
        int rc = tblAppts.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tblAppts.getModel()).removeRow(i);
        }

        ArrayList<Appointment> docList = pp.getAppointments(); //getHosp().getDoctorDirectory().getDoctorList();
        if (docList.isEmpty()) {
            return;
        }
        for (Appointment apt : docList) {
            Object[] row = new Object[4];
            row[0] = apt.getDp();
            row[1] = apt.getMedPlan() == null ? "None" : apt.getMedPlan().getAssociations().keySet();
            row[2] = apt.getTests() == null ? "None" : apt.getTests();
            row[3] = apt.isHasCompleted();
            ((DefaultTableModel) tblAppts.getModel()).addRow(row);
        }
        selectedApt = null;
    }

