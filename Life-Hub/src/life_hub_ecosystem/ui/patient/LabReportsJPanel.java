    void refreshTable() {
//clear supplier table
        int rc = tbCourses.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tbCourses.getModel()).removeRow(i);
        }

        ArrayList<TestReport> testreports = es.getTestReportDirectory().getTrd();//findTest(TOOL_TIP_TEXT_KEY) //getLabTestsList(); //.getMedPlan().getAssociations();
        //ArrayList<TestReport> reports = pp.getTests();
        //ArrayList<LabTest> l3 = new ArrayList<LabTest>();
        //l3.retainAll(l3)
        for (TestReport testReport : testreports) {
            if (testReport.getPp().isMatch(pp.getPerson().getPersonId())) {
                for (LabTest test : testReport.getTestResults().keySet()) {
                    Object[] row = new Object[4];
                    row[0] = test; //.getAssociatedPersonProfile().getPerson().getName();
                    row[1] = testReport.getTestResults().get(test); //(doc).split(",")[0]; //.getDeptName();
                    row[2] = testReport.getTestResultDate();
                    //row[3] = testReport.getLo().getIsActive() ? "Pending" : "Completed";
                    ((DefaultTableModel) tbCourses.getModel()).addRow(row);
                }
            }

        }
        selectedTest = null;
    }

