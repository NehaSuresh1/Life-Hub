    void refreshTable() {
//clear supplier table
        int rc = tbCourses.getRowCount();
        int i;
        for (i = rc - 1; i >= 0; i--) {
            ((DefaultTableModel) tbCourses.getModel()).removeRow(i);
        }
        //HashMap<Med, String> medPlan
        MedPlan medPlan = pp.getActiveMedPlan(); //.getAssociations();
        if (medPlan == null) {
            JOptionPane.showMessageDialog(this, "No Active Med plans!");
            return;
        }
        HashMap<Med, String> mp = medPlan.getAssociations();
        Set<Med> meds = mp.keySet(); //getHosp().getDoctorDirectory().getDoctorList();

        for (Med doc : meds) {

            Object[] row = new Object[4];
            row[0] = doc.getName(); //.getAssociatedPersonProfile().getPerson().getName();
            row[1] = mp.get(doc).split(",")[0]; //.getDeptName();
            row[2] = mp.get(doc).split(",")[1]; //doc.getHighestQulification().getFacultyProfile(); //ua.getAssociatedPersonProfile().getPerson().getName();
            ((DefaultTableModel) tbCourses.getModel()).addRow(row);
        }
        selectedCDoc = null;
    }

